"""Red-green verification of the test suite itself.

A regression test that passes whether or not the fix is present is worthless.
It looks like coverage and provides none. The only way to know is to remove the
safeguard on purpose and confirm the guard turns red.

For each mutation in ``tests/mutations.py`` this runs the named guard twice:

    1. MUTATED — the safeguard is removed. The guard MUST fail.
    2. CLEAN   — nothing removed. The guard MUST pass.

Fail-then-pass is the only accepted result. A guard that stays green while its
safeguard is missing is reported as a HOLE, because that is what it is.

    python scripts/verify_guards.py
    python scripts/verify_guards.py --only negative_weight

Writes ``reports/guard_verification.md``.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))
sys.path.insert(0, str(REPO_ROOT / "tests"))

# The tick marks below are outside cp1252. On a stock Windows console that
# raised UnicodeEncodeError on the first mutation and the gate exited with
# nothing verified, while the child pytest processes were already UTF-8.
for stream in (sys.stdout, sys.stderr):
    if hasattr(stream, "reconfigure"):
        stream.reconfigure(encoding="utf-8", errors="replace")

from mutations import MUTATIONS, ENV_VAR  # noqa: E402

from freight_rate.reporting import markdown_table  # noqa: E402

import pandas as pd  # noqa: E402

PASS, FAIL = "passed", "failed"


def run_guard(selector: str, mutation: str | None) -> tuple[str, str]:
    """Run one pytest selector, optionally under a mutation. Returns (outcome, tail)."""
    environment = dict(os.environ, PYTHONIOENCODING="utf-8")
    environment.pop(ENV_VAR, None)
    if mutation:
        environment[ENV_VAR] = mutation

    completed = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:randomly", "-k", selector],
        cwd=REPO_ROOT,
        env=environment,
        capture_output=True,
        text=True,
    )
    output = (completed.stdout or "") + (completed.stderr or "")
    summary = next(
        (line for line in reversed(output.splitlines()) if "passed" in line or "failed" in line),
        "",
    )
    if "no tests ran" in output or " 0 " in summary and "passed" not in summary:
        return "not-collected", summary.strip()
    return (PASS if completed.returncode == 0 else FAIL), summary.strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", help="run a single mutation by name")
    parser.add_argument("--output", default="reports/guard_verification.md")
    args = parser.parse_args()

    selected = [m for m in MUTATIONS if args.only is None or m.name == args.only]
    if not selected:
        parser.error(f"unknown mutation {args.only!r}")

    print(f"Red-green verification of {len(selected)} guard(s).")
    print("Each guard must FAIL with its safeguard removed, then PASS with it restored.\n")

    rows, holes = [], []
    for mutation in selected:
        print(f"  {mutation.name:<22} removing: {mutation.breaks}")
        mutated, mutated_summary = run_guard(mutation.guard, mutation.name)
        clean, _ = run_guard(mutation.guard, None)

        verdict = "OK" if (mutated == FAIL and clean == PASS) else "HOLE"
        if verdict == "HOLE":
            holes.append(mutation)

        symbol = "✓" if verdict == "OK" else "✗"
        print(f"    {symbol} mutated={mutated:<14} clean={clean:<8} -> {verdict}")
        if verdict == "HOLE":
            print(f"      {mutated_summary}")

        rows.append(
            {
                "mutation": mutation.name,
                "safeguard removed": mutation.breaks,
                "guard": mutation.guard,
                "mutated": mutated,
                "clean": clean,
                "verdict": verdict,
            }
        )

    table = pd.DataFrame(rows).set_index("mutation")
    output = REPO_ROOT / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8") as handle:
        handle.write("# Guard verification (red-green)\n\n")
        handle.write(
            "Each row removes one safeguard from the codebase and re-runs the test that "
            "is supposed to catch it. A guard is only meaningful if it **fails** when its "
            "safeguard is missing and **passes** when it is restored — a test that stays "
            "green either way proves nothing.\n\n"
            "Generated by `python scripts/verify_guards.py`.\n\n"
        )
        handle.write(markdown_table(table, index_label="mutation"))
        handle.write("\n")

    print(f"\n{len(selected) - len(holes)}/{len(selected)} guards verified. wrote {output}")
    if holes:
        print("\nHOLES FOUND — these tests pass even with the safeguard removed:")
        for mutation in holes:
            print(f"  - {mutation.guard}  (should catch: {mutation.breaks})")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
